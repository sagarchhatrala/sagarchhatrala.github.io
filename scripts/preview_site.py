"""Create a local review copy whose navigation works directly from disk."""
from pathlib import Path
import re
import shutil
from urllib.parse import unquote, urlsplit, urlunsplit

from build_site import ROOT, OUTPUT, build

PREVIEW = ROOT / '_preview'


def preview():
    build()
    if PREVIEW.is_symlink() or PREVIEW.resolve() != ROOT.resolve() / '_preview':
        raise RuntimeError('Unsafe preview output path')
    if PREVIEW.exists():
        if not (PREVIEW / '.portfolio-preview').is_file():
            raise RuntimeError('Existing preview is not owned by this builder')
        shutil.rmtree(PREVIEW)
    shutil.copytree(OUTPUT, PREVIEW)
    (PREVIEW / '.portfolio-preview').write_text('Generated by scripts/preview_site.py\n')

    for page in PREVIEW.rglob('*.html'):
        def local_link(match):
            value = match.group(2)
            parts = urlsplit(value)
            if parts.scheme or parts.netloc or not parts.path:
                return match.group(0)
            target = (page.parent / unquote(parts.path)).resolve()
            if not target.is_relative_to(PREVIEW.resolve()):
                raise RuntimeError('Preview link escapes output: ' + value)
            if target.is_dir() and (target / 'index.html').is_file():
                path = parts.path.rstrip('/') + '/index.html'
                value = urlunsplit(('', '', path, parts.query, parts.fragment))
            return match.group(1) + value + match.group(3)

        markup = re.sub(r'(\bhref=")([^"]+)(")', local_link, page.read_text(encoding='utf-8'))
        page.write_text(markup, encoding='utf-8')
    print('Open this file in your browser:')
    print(PREVIEW / 'experience' / 'index.html')


if __name__ == '__main__':
    preview()
