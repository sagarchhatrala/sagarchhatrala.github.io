"""Build only the approved portfolio pages, assets, and machine-readable metadata."""
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / '_site'
ROOT_FILES = ('index.html', 'styles.css', 'app.js', 'llms.txt', 'profile.json', 'robots.txt', 'sitemap.xml')
PROJECT_FILES = {
    'purpose-trace': ('index.html', 'styles.css', 'app.js', 'mark.svg', 'llms.txt', 'project.json', 'evidence.json'),
    'agent-circuit-breaker': ('index.html', 'styles.css', 'app.js', 'mark.svg', 'llms.txt', 'project.json', 'evidence.json'),
    'horizon-agent-containment': ('index.html', 'styles.css', 'app.js', 'mark.svg', 'llms.txt', 'project.json', 'evidence.json'),
}

def build():
    # Refuse to delete anything except this builder's own exact output directory.
    if OUTPUT.is_symlink() or OUTPUT.resolve() != ROOT.resolve() / '_site':
        raise RuntimeError('Unsafe build output path')
    if OUTPUT.exists():
        if not (OUTPUT / '.portfolio-build').is_file():
            raise RuntimeError('Existing output is not owned by this builder')
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    (OUTPUT / '.portfolio-build').write_text('Generated by scripts/build_site.py\n')
    (OUTPUT / '.nojekyll').touch()
    files = list(ROOT_FILES)
    for directory, names in PROJECT_FILES.items():
        files.extend(str(Path(directory) / name) for name in names)
    for asset in (ROOT / 'assets').iterdir():
        if asset.is_file() and asset.suffix.lower() in {'.svg', '.png', '.jpg', '.jpeg', '.ttf', '.woff', '.woff2', '.txt'}:
            files.append(str(asset.relative_to(ROOT)))
    for name in files:
        source = ROOT / name
        if source.is_symlink() or not source.resolve().is_relative_to(ROOT.resolve()):
            raise RuntimeError('Unsafe source path: ' + name)
        target = OUTPUT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    print(f'Built {len(files)} public files with exactly four page entry points.')

if __name__ == '__main__':
    build()
